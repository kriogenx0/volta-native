#!/usr/bin/env python3
"""Generates the Swift and C token files from tokens/tokens.json.

tokens.json is the single source of truth. Run `make tokens` after editing it,
and commit the generated files.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOKENS = json.loads((ROOT / "tokens" / "tokens.json").read_text())
HEADER = "Generated by scripts/gen-tokens.py from tokens/tokens.json. Do not edit."


def camel(*parts):
    first, *rest = parts
    return first + "".join(p[0].upper() + p[1:] for p in rest)


def snake(*parts):
    return "_".join(re.sub(r"(?<!^)(?=[A-Z])", "_", p).upper() for p in parts)


def number(value):
    return repr(float(value))


def swift():
    lines = [f"// {HEADER}", "", "import CoreGraphics", "", "/// Raw design values shared by every Volta-Native app, Swift or C.",
             "public enum VoltaTokens {"]
    for group, values in TOKENS.items():
        for name, value in values.items():
            if group == "color":
                for channel in ("red", "green", "blue"):
                    lines.append(f"    public static let {camel(group, name, channel)}: Double = {number(value[channel])}")
            else:
                kind = "Double" if group in ("opacity", "motion") else "CGFloat"
                lines.append(f"    public static let {camel(group, name)}: {kind} = {number(value)}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def c_header():
    lines = [f"/* {HEADER} */", "#ifndef VOLTA_TOKENS_H", "#define VOLTA_TOKENS_H", ""]
    for group, values in TOKENS.items():
        for name, value in values.items():
            if group == "color":
                for channel in ("red", "green", "blue"):
                    lines.append(f"#define VOLTA_{snake(group, name, channel)} {number(value[channel])}")
            else:
                lines.append(f"#define VOLTA_{snake(group, name)} {number(value)}")
    lines += ["", "#endif /* VOLTA_TOKENS_H */"]
    return "\n".join(lines) + "\n"


(ROOT / "Sources" / "VoltaNative" / "Tokens.swift").write_text(swift())
(ROOT / "include" / "volta_tokens.h").write_text(c_header())
print("Wrote Sources/VoltaNative/Tokens.swift and include/volta_tokens.h")
